import { readFileSync } from "node:fs";
import { call, c, q, sleep } from "./kf.mjs";
const S = JSON.parse(readFileSync(new URL("./proto-state.json", import.meta.url)));
const ids = JSON.parse(readFileSync(new URL("./seeded-ids.json", import.meta.url))).projects;
const P = `/process/2/${c.acc}/ITPMD_Project_Status_Report_A00`;
const p2 = S.projects.find((p) => p.id === "P2");
const r2 = p2.psrs.find((r) => r.status === "Submitted");
const row = { project: { _id: ids.P2 }, reporting_period_month: "2026-09-01", narrative_update: JSON.stringify(r2.narrative) };
const cr = await call("POST", `${P}?${q}`, row, 1);
console.log("create", cr.status, JSON.stringify(cr.body).slice(0, 300));
const id = cr.body?._id, aiid = cr.body?._activity_instance_id;
if (!id) process.exit(1);
await sleep(800);
const g = await call("GET", `${P}/${id}?${q}`); const b = g.body || {};
console.log("detail", g.status, JSON.stringify({ step: b._current_step, aiid: b._activity_instance_id, overall: b.overall_health, sponsor_req: b.sponsor_approval_required, pm: b.RoEGt7NaqKtv?.Name, dh: b.RoEGt7OXkCaE?.Name }));
const a = b._activity_instance_id || aiid;
const sub = await call("POST", `${P}/${id}/${a}/submit?${q}`, { Comment: "" }, 1);
console.log("submit", sub.status, JSON.stringify(sub.body).slice(0, 300));
await sleep(800);
const g2 = await call("GET", `${P}/${id}?${q}`); console.log("after submit:", g2.body?._status, "/", g2.body?._current_step, "/", g2.body?._current_assigned_to?.map?.((x) => x.Name));
